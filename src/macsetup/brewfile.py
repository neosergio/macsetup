"""Brewfile generation and the `brew bundle` driver.

macsetup does not install anything itself. It decides *what* should be
installed and hands a generated Brewfile to Homebrew's bundler, which already
knows about retries, cask quarantine, sudo prompts and upgrade semantics.

Generated files are written to a predictable cache dir and deliberately left
behind after a run, so a failure can be inspected.
"""

from __future__ import annotations

from collections.abc import Iterable
from pathlib import Path

from .manifest import Package
from .runner import Runner

CACHE_DIR = Path.home() / ".cache" / "macsetup" / "brewfiles"


def render(packages: Iterable[Package], *, header: str | None = None) -> str:
    lines: list[str] = []
    if header:
        lines += [f"# {header}", "# generated by macsetup -- edits will be overwritten", ""]
    # Taps and formulae before casks; brew bundle is order-insensitive but this
    # reads far better when you open the file to debug something.
    packages = list(packages)
    lines += [p.brewfile_line() for p in packages if not p.cask and p.mas is None]
    lines += [p.brewfile_line() for p in packages if p.cask]
    lines += [p.brewfile_line() for p in packages if p.mas is not None]
    return "\n".join(lines) + "\n"


def write(module_id: str, packages: Iterable[Package], *, cache_dir: Path | None = None) -> Path:
    directory = cache_dir or CACHE_DIR
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"{module_id}.Brewfile"
    path.write_text(render(packages, header=f"module: {module_id}"), encoding="utf-8")
    return path


def install(runner: Runner, brewfile: Path, *, upgrade: bool = False, jobs: int | None = None):
    """Run `brew bundle install` against a generated Brewfile.

    Homebrew upgrades outdated dependencies by default, which is wrong for
    convergence -- adding one package should not turn into a 40 minute upgrade
    of everything. So `--no-upgrade` unless explicitly asked.
    """
    cmd = ["brew", "bundle", "install", f"--file={brewfile}"]
    if not upgrade:
        cmd.append("--no-upgrade")
    if jobs:
        cmd.append(f"--jobs={jobs}")
    return runner.run(cmd, capture=False)


def check(runner: Runner, brewfile: Path):
    return runner.run(["brew", "bundle", "check", f"--file={brewfile}"])
